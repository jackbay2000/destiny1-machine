"""
destiny1-mk — Capture Card Mode
M&K to virtual DS4 controller bridge. Video comes from your capture card (OBS).
chiaki-ng runs in the background for controller forwarding only.
No focus detection — inputs are always active while F3 capture is on.
Mouse button events are consumed (not passed to other apps) while captured.
"""

